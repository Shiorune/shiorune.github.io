"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const src = fs.readFileSync(require("node:path").join(__dirname,"migrate.js"),"utf8");
new vm.Script(src);
const a = src.indexOf('  const episode = ');
const b = src.indexOf('  try {\n    const prior = ', a);
assert(a >= 0 && b > a);
const f = vm.runInNewContext(src.slice(a,b)+"\n({migratedPath,migrateEntry})");
const old = "/Velune/works/revalna/episodes/012.html";
const expected = "/works/revalna/episodes/012.html";
assert.equal(f.migratedPath(old),expected);
assert.equal(f.migratedPath("/Velune/works/revalna/../../../etc"),null);
assert.equal(f.migratedPath("/Velune/works/_private/episodes/012.html"),null);
assert.equal(f.migratedPath("/Velune/works/revalna/episodes/INDEX.md"),null);
assert.equal(f.migrateEntry("TOKEN","secret"),null);
assert.equal(f.migrateEntry("velune-reader-scroll:"+old,"155")[0],"velune-reader-scroll:"+expected);
assert.equal(f.migrateEntry("velune-reader-scroll:"+old,"155")[1],"155");
const last=f.migrateEntry("velune-reader-last-v2",JSON.stringify({path:old,title:"第12話"}));
assert.equal(JSON.parse(last[1]).path,expected);
const progress=f.migrateEntry("velune-reading-progress-v1:"+old,JSON.stringify({percent:108,finished:true}));
assert.deepEqual(JSON.parse(progress[1]),{percent:100,finished:true});
assert.equal(f.migrateEntry("velune-reading-progress-v1:"+"/Velune/works/no/episodes/abc.html",'{"percent":5}'),null);
const settings=f.migrateEntry("velune-reader-settings-v2",JSON.stringify({fontSize:21,theme:"paper",apiKey:"unsafe"}));
assert.equal(JSON.parse(settings[1]).fontSize,21);
assert.equal("apiKey" in JSON.parse(settings[1]),false);
assert.equal(src.includes('event.origin !== OLD_ORIGIN'),true);
assert.equal(src.includes('event.source !== popup'),true);
console.log("Shiorune import validation passed");
